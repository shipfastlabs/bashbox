beforeEach(function (): void {
    $this->bash = new Bash(new BashOptions(cwd: '/home/user'));

    foreach (['a.txt' => "hello\nworld\n", 'partial' => 'no newline', 'b.txt' => "one\ntwo\nthree\n", 'n.txt' => implode("\n", range(1, 15))."\n", 'sub/x' => "x1\nx2\n"] as $path => $content) {
        $this->bash->writeFile('/home/user/'.$path, $content);
    }
});

$sed = function (string $script, string $stdout, string $stderr = '', int $exitCode = 0): void {
    $result = $this->bash->exec($script);

    expect($result->stdout)->toBe($stdout)
        ->and($result->stderr)->toBe($stderr)
        ->and($result->exitCode)->toBe($exitCode);
};

