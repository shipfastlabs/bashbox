test('sed reports bad options with the usage text', function (string $script, string $message): void {
    $result = $this->bash->exec($script);

    expect($result->stdout)->toBe('')
        ->and($result->stderr)->toBe($message.SED_USAGE)
        ->and($result->exitCode)->toBe(1);
})->with([
    // glibc's getopt wording
    ['sed --s p b.txt', "sed: option '--s' is ambiguous; possibilities: '--silent' '--sandbox' '--separate'\n"],
    ['sed --quiet=x p b.txt', "sed: option '--quiet' doesn't allow an argument\n"],
    ['sed --expression', "sed: option '--expression' requires an argument\n"],
    ['sed --foo', "sed: unrecognized option '--foo'\n"],
    ['sed -k p b.txt', "sed: invalid option -- 'k'\n"],
    ['sed -nk p', "sed: invalid option -- 'k'\n"],
    ['sed -l', "sed: option requires an argument -- 'l'\n"],
    ['sed -e', "sed: option requires an argument -- 'e'\n"],
    ['sed', ''],
]);

test('sed --help prints the usage text', function (): void {
    expect($this->bash->exec('sed --help')->stdout)->toBe(SED_USAGE."E-mail bug reports to: <bug-sed@gnu.org>.\n");
});

test('e runs its command in the sandboxed shell', function (): void {
    // GNU sed runs /bin/sh, which words the error its own way
    $result = $this->bash->exec("echo 'x' | sed 'e'");

    expect($result->stdout)->toBe("\n")
        ->and($result->stderr)->toBe("bash: x: command not found\n")
        ->and($result->exitCode)->toBe(0);
});

test('sed stops scripts that loop without reading input', function (string $script, string $message): void {
    $bash = new Bash(new BashOptions(limits: new Limits(maxOutputSize: 1000, maxStringLength: 1000, maxSedIterations: 50)));

    expect(fn (): \BashBox\BashExecResult => $bash->exec($script))->toThrow(ExecutionLimitException::class, $message);
})->with([
    'branch loop' => ["echo x | sed ':a;ba'", 'sed: iteration limit exceeded'],
    't loop' => ["echo x | sed ':a;s/x/x/;ta'", 'sed: iteration limit exceeded'],
    'T loop' => ["echo x | sed ':a;s/y/y/;Ta'", 'sed: iteration limit exceeded'],
    'D loop' => ["echo x | sed 'G;D'", 'sed: iteration limit exceeded'],
    'growing pattern space' => ["echo x | sed ':a;s/.*/&&/;ta'", 'sed: buffer size limit exceeded'],
    'growing output' => ["seq -s, 30 | sed ':a;p;ba'", 'sed: buffer size limit exceeded'],
]);

test('sed reads long input without hitting the iteration limit', function (): void {
    $bash = new Bash(new BashOptions(limits: new Limits(maxSedIterations: 5)));

    expect($bash->exec("seq 20 | sed ':a;N;\$!ba;s/\\n/,/g'")->stdout)->toBe(implode(',', range(1, 20))."\n");
});
